// Offline. Turns a saved signed AirnodeHub response (from checks/out) into an Aiken constants module for the tests.
// It splits the signed `data` string into fixed text and numeric slots, the shape the validator rebuilds on chain:
//   data = prefix ++ slot0 ++ separator0 ++ slot1 ... ++ suffix
// Run: node checks/05-make-vector.mjs checks/out/meteo-rain-1793355726.json meteo
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { bytesToHex, encodePacked, hashMessage, hexToBytes, keccak256, recoverPublicKey, toHex } from 'viem';
import { publicKeyToAddress } from 'viem/utils';

const [file, name] = process.argv.slice(2);
if (!file || !name) throw new Error('Usage: node checks/05-make-vector.mjs <saved-response.json> <module-name>');
const r = JSON.parse(readFileSync(file, 'utf8'));

const digest = keccak256(encodePacked(['bytes32', 'uint256', 'bytes'], [r.requestHash, BigInt(r.timestamp), toHex(r.data)]));
const messageHash = hashMessage({ raw: digest });
const uncompressed = await recoverPublicKey({ hash: messageHash, signature: r.signature });
if (publicKeyToAddress(uncompressed).toLowerCase() !== r.airnode.toLowerCase()) throw new Error('Recovered signer differs from the response signer');
const pub = hexToBytes(uncompressed);
const compressed = new Uint8Array(33);
compressed[0] = pub[64] & 1 ? 3 : 2;
compressed.set(pub.slice(1, 33), 1);
const signature64 = bytesToHex(hexToBytes(r.signature).slice(0, 64)).slice(2);

// Numeric JSON values only: a number right after a colon and before a comma or the closing brace.
const matches = [...r.data.matchAll(/(?<=:)-?\d+(?:\.\d+)?(?=[,}])/g)];
if (matches.length === 0) throw new Error('No numeric slots found in the signed data');
const hex = (s) => Buffer.from(s, 'utf8').toString('hex');
const prefix = r.data.slice(0, matches[0].index);
const separators = matches.slice(1).map((m, i) => r.data.slice(matches[i].index + matches[i][0].length, m.index));
const last = matches[matches.length - 1];
const suffix = r.data.slice(last.index + last[0].length);
const slots = matches.map((m) => m[0]);

const rebuilt = prefix + slots.map((s, i) => s + (i < separators.length ? separators[i] : '')).join('') + suffix;
if (rebuilt !== r.data) throw new Error('Template does not rebuild the signed data exactly');

const bytes = (h) => `#"${h}"`;
const out = `//// Generated by checks/05-make-vector.mjs from ${file.split('/').pop()}. Real AirnodeHub response, signed by ${r.airnode}.
//// Do not edit by hand.

pub const pubkey: ByteArray = ${bytes(bytesToHex(compressed).slice(2))}

pub const request_hash: ByteArray = ${bytes(r.requestHash.slice(2))}

pub const timestamp: Int = ${r.timestamp}

pub const signature: ByteArray = ${bytes(signature64)}

pub const prefix: ByteArray = ${bytes(hex(prefix))}

pub const separators: List<ByteArray> = [${separators.map((s) => bytes(hex(s))).join(', ')}]

pub const suffix: ByteArray = ${bytes(hex(suffix))}

pub const slots: List<ByteArray> = [${slots.map((s) => bytes(hex(s))).join(', ')}]
`;
const dir = new URL('../aiken/airnode_spike/lib/vectors/', import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL(`${name}.ak`, dir), out);
console.log(`wrote aiken/airnode_spike/lib/vectors/${name}.ak: ${slots.length} slots, prefix ${JSON.stringify(prefix)}, suffix ${JSON.stringify(suffix)}, slots ${JSON.stringify(slots)}`);
